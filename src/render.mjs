// 渲染：给人看的文本战报 + 可以发出去的 SVG 卡片。
//
// 脱敏原则（默认开）：
//   - 项目名只保留最后一段（Users/xxx/project/dsh-plugin → dsh-plugin），不暴露用户名；
//   - 文件只出现 basename 和计数，不出现绝对路径、不出现任何对话内容；
//   - 会话 id 只显示前 8 位。
// 想给同事看完整路径时才用 --show-paths。

const FONT = "-apple-system, BlinkMacSystemFont, 'PingFang SC', 'Helvetica Neue', Arial, sans-serif";

export function shortId(id) {
  return typeof id === 'string' && id.length > 8 ? id.slice(0, 8) : (id ?? '—');
}

/** 项目名脱敏：只留最后一段目录名。 */
export function redactProject(project) {
  if (typeof project !== 'string' || project === '') return '—';
  const parts = project.split('/').filter((part) => part !== '');
  return parts[parts.length - 1] ?? '—';
}

export function formatDuration(minutes) {
  if (minutes < 1) return '<1 分钟';
  if (minutes < 60) return `${minutes} 分钟`;
  const hours = Math.floor(minutes / 60);
  const rest = minutes % 60;
  return rest === 0 ? `${hours} 小时` : `${hours} 小时 ${rest} 分`;
}

export function formatNumber(value) {
  return Number(value ?? 0).toLocaleString('en-US');
}

/** 大数字压缩：1,774,678 → 1.77M，中文语境用万。 */
export function compactNumber(value, lang = 'zh') {
  const n = Number(value ?? 0);
  if (lang === 'zh') {
    if (n >= 100_000_000) return `${(n / 100_000_000).toFixed(2)} 亿`;
    if (n >= 10_000) return `${(n / 10_000).toFixed(1)} 万`;
    return formatNumber(n);
  }
  if (n >= 1_000_000) return `${(n / 1_000_000).toFixed(2)}M`;
  if (n >= 1_000) return `${(n / 1_000).toFixed(1)}K`;
  return formatNumber(n);
}

